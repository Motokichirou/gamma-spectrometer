/*
 * dactest.h — тестовые импульсы ЦАП (самотест тракта без ФЭУ, SPEC §7.7). Переносимый модуль.
 *
 * Цепь: PA4 = DAC1_OUT1 → R307 10 к + C318 100 пФ → вход CR (узел C315/R309). Ступенька ЦАП ΔU
 * вносит заряд ΔU·100 пФ, но ток идёт через (R_ЦАП + R307)·C318 — это НЕ «короче τ», как у ФЭУ.
 * ЦАП — без выходного буфера (dac_test.c: у буфера ограничена скорость нарастания, пик больших
 * ступенек сжимался на 3.5 %). Импульс на АЦП (замер на плате 2026-11-06): фронт за 1–2 отсчёта,
 * спад с τ ≈ 8 отсчётов (2.3 мкс), выше порога ≈ 45 отсчётов при ступеньке 3000 (у ФЭУ — 3–4).
 * Поэтому для ЦАП детектор переходит в режим самотеста (свой эталон формы tpl_dac.h, ширина до
 * DACT_MAXW, база заморожена — приложение, main.c). Масштаб ≈ 0.72 кода АЦП на код ЦАП (пик),
 * вся шкала ЦАП (3695 → ≈ 2660 кодов) помещается в АЦП (потолок над базой 645 — ≈ 3450).
 *
 * Форма серии: ступенька ВВЕРХ на step (её ловит детектор), DACT_HOLD_US ожидания (импульс
 * отзвучал), затем спуск лесенкой по ≤ DACT_DN_MAX кодов через DACT_DN_US. Почему не одной
 * ступенькой вниз (как было до 2026-11-06): ступенька вниз больше ≈ 570 кодов загоняет АЦП и ОУ
 * в 0 (база 645), после этого и после долгого «верха» (полпериода) медленный хвост тракта
 * (τ ≈ 330 мкс, ≈ 0.5 % амплитуды) держит выход выше порога на сотни мкс — ложные триггеры
 * и медленный путь детектора на каждом отсчёте (потеря порций). Каждая ступенька лесенки —
 * отрицательный импульс ≤ ≈ 300 кодов (без насыщения), хвост ∝ DACT_HOLD_US / 330 мкс — ≤ 1 код.
 *
 * Здесь — логика без железа: разбор команды и машина состояний таймера (dact_tick зовётся из
 * прерывания таймера, на ПК — из теста). Железо — src/hw/dac_test.c (TIM6 156 МГц без деления,
 * DAC1 без триггера: запись DHR → выход через такт).
 *
 * Последовательность: ЦАП включается на DACT_BASE (выход из Hi-Z — сам по себе ступенька,
 * поэтому первая пауза DACT_SETTLE_US), затем n раз: вверх на step, через hold — ndn ступенек
 * вниз через dn, после последней (код DACT_BASE) — пауза rest + случайная добавка 0…jit−1 тактов
 * до следующего подъёма; период подъёмов = period_us (+ добавка). После последнего импульса — ещё
 * rest, и конец: ЦАП выкл, PA4 — аналоговый вход (Hi-Z), как требует SPEC §7.7 для набора.
 * Прерываний на импульс: 1 + ndn (≤ 14).
 *
 * Случайная добавка: шаг таймера 1 такт ЦП, отсчёт АЦП = jit тактов (45 при 2.5 такта
 * выборки, 57 при 6.5). Без добавки период импульсов кратен такту и фаза ступеньки относительно
 * отсчётов АЦП перебирает лишь несколько значений (100 мкс = 15 600 тактов ≡ 30 mod 45 ⇒ 3 фазы);
 * с равномерной добавкой 0…jit−1 фаза равномерна — проверяется вся таблица эталона.
 *
 * Команды (dact_handle; ответ одной строкой, proto допишет \r\n):
 *   -dac <код> <n> [период_мкс] → "-ok dac step=<код> n=<n> period=<мкс>"; код 1…DACT_STEP_MAX,
 *                                 n 1…65535, период DACT_PER_MIN…DACT_PER_MAX (по умолчанию
 *                                 DACT_PER_DEF) и не меньше dact_per_min(код) — иначе
 *                                 "-err dac period>=<мкс>". Занято — "-err dac busy". По окончании
 *                                 приложение шлёт текст "-ok dac done <n>".
 *   -dac                        → "-ok dac idle" / "-ok dac busy done=<k> n=<n>"
 *   -dac off                    → остановить: "-ok dac off done=<k>"
 *   Разрешено и в наборе (для того и нужно: пик в спектре), и при включённом ВВ.
 */
#ifndef DACTEST_H
#define DACTEST_H

#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>

#define DACT_BASE       400u     /* код покоя ≈ 0.24 В (запас от 0; ЦАП без буфера линеен от 0) */
#define DACT_STEP_MAX   (4095u - DACT_BASE)
#define DACT_PER_MIN    45u      /* мкс: hold + rest при одной ступеньке вниз (= dact_per_min(≤ 300)) */
#define DACT_PER_MAX    800u     /* мкс: пауза rest + добавка ≤ 65535 тактов при 156 МГц */
#define DACT_HOLD_US    25u      /* мкс от подъёма до спуска: импульс (τ ≈ 2.3 мкс) спал до 0.1 % */
#define DACT_DN_MAX     300u     /* кодов на ступеньку спуска: ≈ −220…−300 кодов АЦП, без насыщения */
#define DACT_DN_US      3u       /* мкс между ступеньками спуска */
#define DACT_REST_MIN_US 20u     /* мкс тишины от конца спуска до следующего подъёма (база) */
#define DACT_MAXW       64u      /* ширина импульса ЦАП выше порога, отсчётов (3695 кодов ≈ 50) */
#define DACT_THR        24u      /* порог детектора в режиме ЦАП, коды: хвост после спуска ≤ +9 при
                                    3695, + 5σ шума; наименьшая видимая ступенька ≈ 50 кодов */
#define DACT_PER_DEF    100u
#define DACT_SETTLE_US  400u     /* пауза после включения ЦАП до первой ступеньки (таймер 16 бит) */

typedef enum { DACT_IDLE = 0, DACT_SETTLE, DACT_DOWN, DACT_LOW, DACT_TAIL } dact_phase_t;

/* ступенек спуска для step и наименьший период, мкс */
uint16_t dact_ndn(uint16_t step);
uint16_t dact_per_min(uint16_t step);

typedef struct {
    uint16_t step, n, period_us;
    uint32_t hold;               /* тактов от подъёма до первой ступеньки вниз */
    uint32_t dn;                 /* тактов между ступеньками вниз */
    uint32_t rest;               /* тактов от последней ступеньки вниз до подъёма (без добавки) */
    uint32_t settle;             /* тактов первой паузы */
    uint32_t wait;               /* остаток паузы (rest + добавка дробится по 65536 тактов) */
    uint16_t ndn, k;             /* ступенек вниз; выдано в текущем спуске */
    uint16_t jit;                /* добавка 0…jit−1 тактов к паузе после спада */
    uint32_t rnd;                /* xorshift32 */
    volatile uint16_t done;      /* ступенек вверх выдано (читает главный цикл) */
    volatile uint8_t  phase;     /* dact_phase_t */
} dact_t;

/* Подготовить серию. tick_hz — такт таймера, jit — тактов таймера на отсчёт АЦП (≥ 1).
   false — параметры вне пределов (dact_t не тронут). После true: железо пишет DACT_BASE в ЦАП,
   включает его и запускает таймер с первым интервалом d->settle. */
bool dact_start(dact_t *d, uint16_t step, uint16_t n, uint16_t period_us, uint32_t tick_hz, uint16_t jit);

/* Шаг машины (из прерывания таймера по окончании интервала). true — записать *code в ЦАП и
   следующий интервал *ticks (≥ 1); false — серия окончена: ЦАП и таймер выключить. */
bool dact_tick(dact_t *d, uint16_t *code, uint32_t *ticks);

static inline bool dact_busy(const dact_t *d) { return d->phase != DACT_IDLE; }
/* Принудительный конец (команда -dac off); железо выключает таймер ДО вызова. */
void dact_abort(dact_t *d);

/* приложение для команд */
typedef struct {
    bool     (*start)(uint16_t step, uint16_t n, uint16_t period_us);   /* false — занято/сбой */
    void     (*stop)(void);
    bool     (*busy)(void);
    uint16_t (*done)(void);
    uint16_t (*total)(void);
} dact_ctx_t;

/* true — команда -dac (ответ в reply), false — не наша. */
bool dact_handle(const dact_ctx_t *c, const char *cmd, char *reply, size_t cap);

#endif
