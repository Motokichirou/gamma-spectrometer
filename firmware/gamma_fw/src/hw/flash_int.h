/* flash_int.h — настройки во внутренней флеш (SPEC §7.9, §9).
 *
 * Одна страница 4 КБ по адресу 0x0801 F000 — последняя у 128 КБ при DBANK = 0 (один банк).
 * Линкер (gamma_fw.ld) отдаёт программе только 124 КБ — страница в образ не попадает,
 * перепрошивка по `-w` её не стирает (CubeProgrammer стирает только страницы под файлом).
 * При DBANK = 1 у 128 КБ этот адрес — дыра в адресном пространстве (Bank 2 с 0x0804 0000,
 * RM0440 Табл. 7): и чтение, и запись отказываются, а не лезут наугад.
 *
 * Стирание страницы останавливает ЦП на ~22 мс (до 40 мс): код и векторы прерываний — во флеш.
 * ШИМ ВВ (TIM1) и DMA идут сами; принятое по UART за это время может потеряться (FIFO 8 байт).
 * Поэтому писать только при остановленном наборе — это гарантирует proto (settings_commit).
 */
#ifndef FLASH_INT_H
#define FLASH_INT_H
#include <stdbool.h>
#include "settings.h"

#define FLASH_SETTINGS_ADDR 0x0801F000u
#define FLASH_SETTINGS_PAGE 31u               /* (0x0801 F000 − 0x0800 0000) / 4 КБ */

/* true — DBANK = 0 и флеш ≥ 128 КБ: страница настроек на месте */
bool flash_layout_ok(void);
/* Читает страницу; true — settings_valid прошёл, *s заполнен; иначе false, *s не тронут. */
bool flash_settings_load(settings_t *s);
/* Стирание + запись двойными словами + сверка чтением (core/flashstore). Если на странице уже
   то же самое — ничего не делает. Вызывать ТОЛЬКО при остановленном наборе. */
bool flash_settings_store(const settings_t *s);

#endif
