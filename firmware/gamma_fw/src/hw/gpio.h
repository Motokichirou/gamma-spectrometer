/* gpio.h — безопасное состояние выводов (SPEC §1, §3). */
#ifndef GPIO_H
#define GPIO_H

/* ПЕРВЫМ после сброса: PB10 (HV_ENABLE) = 0, PA8 (HV_CONTROL) = 0, PB6 (D102) = 0 — выходы
   push-pull; прочие выводы GPIOA/B/C — в аналог (как после сброса), кроме оставленных как есть:
   PA13/PA14 (SWD), PA15/PB3/PB4 (W25Q64: CS держит подтяжка вверх по сбросу — Task 12).
   Нужна и после перехода из системного загрузчика по Go: он мог оставить PA8 как I2C2_SDA
   с подтяжкой вверх, USART1 на PA9/PA10 и т. п. */
void gpio_safe_init(void);

/* ВВ выкл немедленно: PB10 = 0, PB6 = 0, PA8 — выход 0 (из AF ШИМ). Без стека и прерываний —
   годится в обработчике сбоя и перед переходом в загрузчик. Таймер TIM1 не трогает. */
void gpio_hv_force_off(void);

#endif
