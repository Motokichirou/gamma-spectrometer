"""Систематика, ОДИНАКОВАЯ для обеих ветвей (csp.py и tia.py).

Модель: заряд события Q неизменен (световыход от температуры одинаково действует на обе
ветви и закрывается стабилизацией усиления — здесь НЕ моделируется), меняется только
ПОСТОЯННАЯ ВЫСВЕЧИВАНИЯ td реального события. Эталон и полюс-нуль в обработке обеих
ветвей остаются на номинальных 230 нс — как в стендах.

Коэффициент NaI(Tl): −0.3…−0.5 %/°C по td; берём 0.4 %/°C, ±10 °C ⇒ ±4 %.

  none        td = 230 нс у всех
  static:+4   td = 230·(1+0.04) у всех (кристалл на 10 °C холоднее точки снятия эталона)
  static:-4   то же, на 10 °C теплее
  drift:4     td равномерно в 230·(1±0.04) по событиям: набор спектра при температуре,
              гуляющей ±10 °C, без стабилизатора

Отдельный ГСЧ (seed + 7777): моменты, амплитуды и шум остаются бит в бит теми же,
что и в прогоне без систематики, — сравнение на общих случайных числах.

Медленная компонента (баллистический дефицит): доля `slow` с постоянной 1.0 мкс.
Для NaI(Tl) величина её в литературе разная; здесь это стресс-тест, одинаковый
для обеих ветвей.
"""
import numpy as np

T_SLOW = 1.0e-6


def draw_td(seed, n_ev, t_ev, dur, mode, td0):
    if mode in (None, '', 'none'):
        return np.full(n_ev, td0)
    kind, val = mode.split(':')
    p = float(val) / 100.0
    if kind == 'static':
        return np.full(n_ev, td0 * (1 + p))
    if kind == 'drift':
        r = np.random.default_rng(seed + 7777)
        return td0 * (1 + p * (2 * r.random(n_ev) - 1))
    raise ValueError(mode)


def slow_frac(slow):
    return float(slow), T_SLOW


def unique_match(t_ev, et, tol):
    """Сопоставление оценок с истинными событиями: ближайшее в пределах tol, и КАЖДОЕ
    истинное событие засчитывается не более одного раза (ближайшей оценкой).
    В исходных стендах уникальности нет: дубликат одного события засчитывался дважды
    и мог дать светимость > 100 %. Применяется к обеим ветвям одинаково."""
    n_ev = len(t_ev)
    k = np.clip(np.searchsorted(t_ev, et), 1, max(1, n_ev - 1))
    pick = np.where(np.abs(t_ev[k] - et) < np.abs(t_ev[k - 1] - et), k, k - 1)
    dist = np.abs(t_ev[pick] - et)
    ok = dist < tol
    order = np.lexsort((dist, pick))
    seen = set()
    for i in order:
        if not ok[i]:
            continue
        if pick[i] in seen:
            ok[i] = False
        else:
            seen.add(pick[i])
    return pick, ok
